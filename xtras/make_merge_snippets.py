#!/usr/bin/env python3
"""
Generates the merge inputs for apply_merged_uz5.ps1 from the two ORIGINAL packs (read only):
  xtras/merge_imports.txt                      files copied from the Revised pack (logical name missing in Main)
  xtras/Wadfusion-Xtras-merged_uz5/_append/*   definition entries that only the Revised pack has (Main wins on conflicts)

Rules (see xtras/MERGE_NOTES.md):
  * graphics / patches / sounds: imported when the same namespace:name does not exist in Main
  * sprites: imported only when Main has no sprite with that 4-letter prefix (frames of one sprite must come from one source)
  * music: only content Main does not have (identical content under another name is not duplicated)
  * FONTDEFS, SNDINFO, ANIMDEFS, TEXTURES, LANGUAGE: only keys Main lacks
"""
import argparse, os, re, sys, zipfile, hashlib, collections


def norm(n):
    n = n.replace('\\', '/')
    low = n.lower()
    for p in ('wadfusion-xtras-main/', 'wadfusion-xtras-revised_beta/'):
        if low.startswith(p):
            return n[len(p):]
    return n


def load(path):
    z = zipfile.ZipFile(path)
    files = {}
    for i in z.infolist():
        if i.filename.endswith('/'):
            continue
        files[norm(i.filename).lower()] = (norm(i.filename), i)
    return z, files


def text(z, entry):
    return z.read(entry).decode('cp1252', errors='replace')


def logical(p):
    top = p.split('/')[0].lower() if '/' in p else ''
    if top in ('sprites', 'sounds', 'music', 'graphics', 'patches', 'flats'):
        return top + ':' + os.path.splitext(p.split('/')[-1])[0].lower()
    return ''


def find(files, name):
    for k, v in files.items():
        if k == name.lower():
            return v
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--main', required=True)
    ap.add_argument('--revised', required=True)
    ap.add_argument('--out', default='xtras')
    a = ap.parse_args()
    zm, fm = load(a.main)
    zr, fr = load(a.revised)

    main_log = collections.defaultdict(list)
    main_sha = set()
    main_pref = set()
    for k, (n, i) in fm.items():
        lg = logical(n)
        if lg:
            main_log[lg].append(n)
        if n.lower().startswith('sprites/'):
            main_pref.add(os.path.splitext(n.split('/')[-1])[0][:4].lower())
    for k, (n, i) in fm.items():
        main_sha.add(i.CRC)

    imports, notes = [], []
    for k in sorted(fr):
        n, i = fr[k]
        lg = logical(n)
        if not lg or i.file_size == 0:
            continue
        ns = lg.split(':')[0]
        if lg in main_log:
            continue
        if ns == 'sprites':
            if os.path.splitext(n.split('/')[-1])[0][:4].lower() in main_pref:
                notes.append('skip sprite (prefix exists in Main): ' + n)
                continue
        elif ns == 'music':
            # identical audio already present in Main under another name is not duplicated
            if i.CRC in main_sha:
                notes.append('skip music (same audio already in Main): ' + n)
                continue
        imports.append(n)

    # Root-level wads that no engine loads from inside a pack: keep as reference copies
    archive = []
    for nm in ('d2spfx20.wad', 'misctextures.wad'):
        r = find(fr, nm)
        if r:
            archive.append((r[0], 'Revised_Archive/' + r[0]))
    # Episode 4 part 2 intermission (belongs with the E4 art)
    r = find(fr, 'in_ep42.txt')
    if r and not find(fm, 'in_ep42.txt'):
        imports.append(r[0])

    with open(os.path.join(a.out, 'merge_imports.txt'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('# Generated by xtras/make_merge_snippets.py. Files copied from the Revised pack into the merged pack.\n')
        f.write('# "src" or "src => dest". Main wins: an existing destination is never replaced.\n')
        for n in imports:
            f.write(n + '\n')
        for s, d in archive:
            f.write('%s => %s\n' % (s, d))
    print('imports:', len(imports), 'archive copies:', len(archive), 'skipped notes:', len(notes))
    for n in notes[:10]:
        print('  ', n)

    # ---- definition snippets
    ap_dir = os.path.join(a.out, 'Wadfusion-Xtras-merged_uz5', '_append')
    os.makedirs(ap_dir, exist_ok=True)

    def write(rel, content):
        path = os.path.join(ap_dir, rel.replace('/', os.sep))
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w', encoding='cp1252', errors='replace', newline='') as f:
            f.write(content)
        print('append', rel, len(content), 'chars')

    new_dir = os.path.join(a.out, 'Wadfusion-Xtras-merged_uz5', '_new')
    os.makedirs(new_dir, exist_ok=True)

    def write_new(rel, content):
        with open(os.path.join(new_dir, rel), 'w', encoding='cp1252', errors='replace', newline='') as f:
            f.write(content)
        print('new file', rel, len(content), 'chars')

    # FONTDEFS: whole named blocks that Main does not define
    def font_blocks(t):
        return {m.group(1).lower(): m.group(0) for m in re.finditer(r'(?ims)^\s*(\w+)\s*\n\s*\{.*?\n\s*\}', t)}
    rm, rr = find(fm, 'fontdefs'), find(fr, 'fontdefs')
    if rm and rr:
        bm, br = font_blocks(text(zm, rm[1])), font_blocks(text(zr, rr[1]))
        new = [br[k] for k in br if k not in bm]
        write(rm[0], '\r\n// ---- fonts merged from Xtras Revised beta\r\n' + '\r\n\r\n'.join(b.strip() for b in new).replace('\n', '\r\n') + '\r\n')

    # SNDINFO: lines Main lacks (Main splits SNDINFO over SNDINFO.* lumps; a new SNDINFO.RevisedMerge lump is added)
    main_snd = ''.join(text(zm, i) + chr(10) for k, (n, i) in fm.items() if os.path.basename(n).lower().startswith('sndinfo'))
    rr = find(fr, 'sndinfo')
    if rr:
        norm_l = lambda l: ' '.join(l.split()).lower()
        mlines = {norm_l(l) for l in main_snd.splitlines() if l.strip()}
        mtok = {norm_l(l).split()[0] for l in main_snd.splitlines() if l.strip() and not l.strip().startswith(('//', '$'))}
        new = []
        for l in text(zr, rr[1]).splitlines():
            if l.strip() and not l.strip().startswith('//') and norm_l(l) not in mlines:
                new.append(l.rstrip())
        crlf = chr(13) + chr(10)
        write_new('SNDINFO.RevisedMerge', '// Sounds that only the Xtras Revised beta defines (merged by xtras/make_merge_snippets.py)' + crlf + crlf.join(new) + crlf)

    # LANGUAGE: keys Main lacks, per language section
    rm, rr = find(fm, 'language'), find(fr, 'language')
    if rm and rr:
        def keys(t):
            out, lang = {}, 'default'
            for line in t.splitlines():
                m = re.match(r'\s*\[([^\]]*)\]', line)
                if m:
                    lang = m.group(1).strip().lower(); continue
                m = re.match(r'\s*([A-Za-z0-9_$]+)\s*=\s*(.*)', line)
                if m:
                    out.setdefault(lang, {})[m.group(1).lower()] = line.rstrip()
            return out
        km, kr = keys(text(zm, rm[1])), keys(text(zr, rr[1]))
        # keep the header of each language section as the Revised file spells it
        hdr = {}
        for line in text(zr, rr[1]).splitlines():
            m = re.match(r'\s*(\[([^\]]*)\])', line)
            if m:
                hdr[m.group(2).strip().lower()] = m.group(1)
        # The Revised-only keys are old TNT/Plutonia music names, pistol-start strings (replaced by WadFusion's own
        # option) and one level name; nothing in the merged pack reads them, so only keys with a prefix listed in
        # LANGUAGE_KEEP are merged. The decision for every skipped key is in MERGE_NOTES.md.
        LANGUAGE_KEEP = ()
        out = ['', '// ---- strings merged from Xtras Revised beta']
        added = 0
        for lang, d in kr.items():
            add = [v for k, v in d.items() if k not in km.get(lang, {}) and k.startswith(LANGUAGE_KEEP)]
            if add:
                out.append(hdr.get(lang, '[%s]' % lang))
                out.extend(add)
                added += len(add)
        stale = os.path.join(ap_dir, rm[0].replace('/', os.sep))
        if added:
            write(rm[0], '\r\n'.join(out) + '\r\n')
        elif os.path.exists(stale):
            os.remove(stale)

    # ANIMDEFS: texture/flat entries Main lacks
    rm, rr = find(fm, 'animdefs.txt'), find(fr, 'animdefs.txt')
    if rm and rr:
        def anim_names(t):
            return {m.group(1).lower() for m in re.finditer(r'(?im)^\s*(?:texture|flat)\s+(?:optional\s+)?"?(\w+)"?', t)}
        have = anim_names(text(zm, rm[1]))
        blocks = re.split(r'(?im)^(?=\s*(?:texture|flat)\s)', text(zr, rr[1]))
        new = []
        for b in blocks:
            m = re.match(r'(?im)\s*(?:texture|flat)\s+(?:optional\s+)?"?(\w+)"?', b)
            if m and m.group(1).lower() not in have:
                new.append(b.rstrip())
        if new:
            write(rm[0], '\r\n// ---- animations merged from Xtras Revised beta\r\n' + '\r\n'.join(new).replace('\n', '\r\n') + '\r\n')

    # TEXTURES: whole definitions Main lacks (Main splits TEXTURES over TEXTURES.* lumps)
    nl, crlf = chr(10), chr(13) + chr(10)
    name_re = r'(?:Texture|Sprite|Graphic|WallTexture|Flat)\s+(?:optional\s+)?"?([\w]+)"?'
    main_tex = ''.join(text(zm, i) + nl for k, (n, i) in fm.items() if os.path.basename(n).lower().startswith('textures'))
    have = {m.group(1).lower() for m in re.finditer(r'(?im)^\s*' + name_re, main_tex)}
    new = []
    for k, (n, i) in sorted(fr.items()):
        if os.path.basename(n).lower().startswith('textures') and not n.lower().endswith('.wad'):
            for m in re.finditer(r'(?ims)^\s*((?:Texture|Sprite|Graphic|WallTexture|Flat)\s+(?:optional\s+)?"?([\w]+)"?[^{]*\{.*?' + nl + r'\})', text(zr, i)):
                if m.group(2).lower() not in have:
                    have.add(m.group(2).lower())
                    new.append(m.group(1))
    if new:
        write_new('TEXTURES.RevisedMerge', '// Texture definitions that only the Xtras Revised beta has' + crlf + (crlf + crlf).join(x.replace(nl, crlf) for x in new) + crlf)


if __name__ == '__main__':
    main()
